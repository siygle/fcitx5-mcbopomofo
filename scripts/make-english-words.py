#!/usr/bin/env python3
"""Generate data/plus-english.txt from a SCOWL/ESDB wordlist (MIT-like).

Usage: scripts/make-english-words.py <words.txt> <out>
  words.txt: https://app.aspell.net/create (size 50, US, special=hacker)

Keeps ASCII words of 2-30 letters (apostrophe forms such as "AA's" dropped).
When a word appears in several casings ("apple", "Apple"), all are kept; the
engine shows the lowercase/most common form first and offers the rest.
"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
ok = re.compile(r"^[A-Za-z][A-Za-z0-9.+#-]{1,29}$")
seen, words = set(), []
with open(src, encoding="utf-8") as f:
    for w in (l.strip() for l in f):
        if ok.match(w) and w not in seen:
            seen.add(w); words.append(w)
with open(out, "w", encoding="utf-8") as f:
    f.write("# English words from SCOWL/ESDB (size 50, US, hacker), Copyright 2000-2026 Kevin Atkinson.\n")
    f.write("# See LICENSE.scowl. Generated by scripts/make-english-words.py; do not edit.\n")
    f.write("# Custom words: ~/.local/share/fcitx5/mcbopomofo/plus-english.txt (one per line).\n")
    for w in words: f.write(w + "\n")
print(len(words), "words")
