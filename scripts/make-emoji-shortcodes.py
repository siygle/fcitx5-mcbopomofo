#!/usr/bin/env python3
"""Generate data/plus-emoji-shortcodes.txt from GitHub gemoji (MIT).

Usage: scripts/make-emoji-shortcodes.py <gemoji emoji.json> <out>
  emoji.json: https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json

Output: one "shortcode<TAB>emoji<TAB>space-separated tags" per line, sorted
by shortcode. Only [a-z0-9_+-] shortcodes are kept (they're typed on a QWERTY
keyboard while the IME is in Bopomofo mode).
"""
import json, re, sys
src, out = sys.argv[1], sys.argv[2]
ok = re.compile(r"^[a-z0-9_+\-]{1,40}$")
rows = {}
with open(src, encoding="utf-8") as f:
    for e in json.load(f):
        emoji = e.get("emoji", "")
        if not emoji or len(emoji) > 16:
            continue
        tags = " ".join(t for t in e.get("tags", []) if ok.match(t))
        for alias in e.get("aliases", []):
            if ok.match(alias) and alias not in rows:
                rows[alias] = (emoji, tags)
with open(out, "w", encoding="utf-8") as f:
    f.write("# Emoji shortcodes from GitHub gemoji (MIT, Copyright (c) 2019 GitHub, Inc.)\n")
    f.write("# Generated by scripts/make-emoji-shortcodes.py. Do not edit; put custom\n")
    f.write("# shortcodes in ~/.local/share/fcitx5/mcbopomofo/plus-emoji-shortcodes.txt\n")
    for code in sorted(rows):
        emoji, tags = rows[code]
        f.write(f"{code}\t{emoji}\t{tags}\n")
print(len(rows), "shortcodes")
